ALTER SESSION SET "_ORACLE_SCRIPT" = TRUE;
-- DROP USER CAFE_CATCHTABLE CASCADE;
-- 사용자 생성
CREATE USER CAFE_CATCHTABLE
IDENTIFIED BY 1234
DEFAULT TABLESPACE USERS
TEMPORARY TABLESPACE TEMP;

-- 요청하신 권한 부여
GRANT CONNECT, RESOURCE, DBA TO CAFE_CATCHTABLE;

-- USERS 테이블스페이스 사용량 제한 해제
ALTER USER CAFE_CATCHTABLE QUOTA UNLIMITED ON USERS;

SET SERVEROUTPUT ON;

--------------------------------------------------------------------------------
-- 테이블 7개 생성
--------------------------------------------------------------------------------

CREATE TABLE MEMBER (
    MEMBER_ID   VARCHAR2(50)  NOT NULL,
    PASSWORD    VARCHAR2(100) NOT NULL,
    NAME        VARCHAR2(50)  NOT NULL,
    PHONE       VARCHAR2(20)  NOT NULL,
    ROLE        VARCHAR2(10)  DEFAULT 'USER' NOT NULL,
    CREATED_AT  DATE          DEFAULT SYSDATE NOT NULL,
    CONSTRAINT PK_MEMBER PRIMARY KEY (MEMBER_ID),
    CONSTRAINT CK_MEMBER_ID_FORMAT CHECK (
        REGEXP_LIKE(MEMBER_ID, '^[A-Za-z0-9]{4,20}$')
    ),
    CONSTRAINT CK_MEMBER_ROLE CHECK (ROLE IN ('USER', 'OWNER')),
    CONSTRAINT CK_MEMBER_PHONE CHECK (
        REGEXP_LIKE(PHONE, '^010-[0-9]{4}-[0-9]{4}$')
    )
);

CREATE TABLE OWNER (
    OWNER_ID     VARCHAR2(50) NOT NULL,
    BUSINESS_NUM VARCHAR2(50) NOT NULL,
    CONSTRAINT PK_OWNER PRIMARY KEY (OWNER_ID),
    CONSTRAINT FK_OWNER_MEMBER FOREIGN KEY (OWNER_ID)
        REFERENCES MEMBER (MEMBER_ID),
    CONSTRAINT UK_OWNER_BUSINESS_NUM UNIQUE (BUSINESS_NUM),
    CONSTRAINT CK_OWNER_BUSINESS_NUM CHECK (
        REGEXP_LIKE(BUSINESS_NUM, '^[0-9]{3}-[0-9]{2}-[0-9]{5}$')
    )
);

CREATE TABLE CAFE (
    CAFE_ID        NUMBER GENERATED BY DEFAULT AS IDENTITY,
    OWNER_ID       VARCHAR2(50)  NOT NULL,
    CAFE_NAME      VARCHAR2(100) NOT NULL,
    ADDRESS        VARCHAR2(255) NOT NULL,
    PHONE          VARCHAR2(20)  NOT NULL,
    START_TIME     VARCHAR2(5)   NOT NULL,
    END_TIME       VARCHAR2(5)   NOT NULL,
    OPERATING_DAYS VARCHAR2(100) NOT NULL,
    CONSTRAINT PK_CAFE PRIMARY KEY (CAFE_ID),
    CONSTRAINT FK_CAFE_OWNER FOREIGN KEY (OWNER_ID)
        REFERENCES OWNER (OWNER_ID),
    CONSTRAINT CK_CAFE_START_TIME CHECK (
        REGEXP_LIKE(START_TIME, '^([01][0-9]|2[0-3]):[0-5][0-9]$')
    ),
    CONSTRAINT CK_CAFE_END_TIME CHECK (
        REGEXP_LIKE(END_TIME, '^([01][0-9]|2[0-3]):[0-5][0-9]$')
    ),
    CONSTRAINT CK_CAFE_TIME_ORDER CHECK (END_TIME > START_TIME)
);

CREATE TABLE ZONE (
    ZONE_ID   NUMBER GENERATED BY DEFAULT AS IDENTITY,
    CAFE_ID   NUMBER       NOT NULL,
    ZONE_NAME VARCHAR2(50) NOT NULL,
    CONSTRAINT PK_ZONE PRIMARY KEY (ZONE_ID),
    CONSTRAINT FK_ZONE_CAFE FOREIGN KEY (CAFE_ID)
        REFERENCES CAFE (CAFE_ID)
);

CREATE TABLE SEAT (
    SEAT_ID    NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ZONE_ID    NUMBER       NOT NULL,
    SEAT_NUM   VARCHAR2(20) NOT NULL,
    SEAT_TYPE  VARCHAR2(50) NOT NULL,
    STATUS     VARCHAR2(20) DEFAULT '빈자리' NOT NULL,
    EXTRA_ITEM VARCHAR2(255),
    CAPACITY   NUMBER       NOT NULL,
    CONSTRAINT PK_SEAT PRIMARY KEY (SEAT_ID),
    CONSTRAINT FK_SEAT_ZONE FOREIGN KEY (ZONE_ID)
        REFERENCES ZONE (ZONE_ID),
    CONSTRAINT UK_SEAT_ZONE_NUM UNIQUE (ZONE_ID, SEAT_NUM),
    CONSTRAINT CK_SEAT_CAPACITY CHECK (CAPACITY >= 1),
    CONSTRAINT CK_SEAT_STATUS CHECK (
        STATUS IN ('빈자리', '예약됨', '이용중', '사용중지')
    )
);

CREATE TABLE RESERVATION (
    RESERVATION_ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    MEMBER_ID      VARCHAR2(50) NOT NULL,
    SEAT_ID        NUMBER       NOT NULL,
    START_DT       DATE         NOT NULL,
    END_DT         DATE         NOT NULL,
    VISITOR_COUNT  NUMBER       NOT NULL,
    STATUS         VARCHAR2(20) DEFAULT '예약완료' NOT NULL,
    ACTUAL_IN      DATE,
    ACTUAL_OUT     DATE,
    CREATED_AT     DATE         DEFAULT SYSDATE NOT NULL,
    CONSTRAINT PK_RESERVATION PRIMARY KEY (RESERVATION_ID),
    CONSTRAINT FK_RESV_MEMBER FOREIGN KEY (MEMBER_ID)
        REFERENCES MEMBER (MEMBER_ID),
    -- 유효 예약이 없는 좌석을 삭제할 때 과거 예약행은 함께 삭제되고,
    -- RESERVATION_LOG에는 이력이 남도록 합니다.
    CONSTRAINT FK_RESV_SEAT FOREIGN KEY (SEAT_ID)
        REFERENCES SEAT (SEAT_ID) ON DELETE CASCADE,
    CONSTRAINT CK_RESV_DATE CHECK (END_DT > START_DT),
    CONSTRAINT CK_RESV_STATUS CHECK (
        STATUS IN ('예약완료', '이용중', '이용완료', '예약취소', '노쇼')
    )
);

CREATE TABLE RESERVATION_LOG (
    LOG_ID         NUMBER GENERATED BY DEFAULT AS IDENTITY,
    RESERVATION_ID NUMBER       NOT NULL,
    ACTION         VARCHAR2(10) NOT NULL,
    OLD_STATUS     VARCHAR2(20),
    NEW_STATUS     VARCHAR2(20),
    CHANGED_AT     DATE DEFAULT SYSDATE NOT NULL,
    CONSTRAINT PK_RESERVATION_LOG PRIMARY KEY (LOG_ID),
    CONSTRAINT CK_RESV_LOG_ACTION CHECK (ACTION IN ('INSERT', 'UPDATE', 'DELETE'))
);


