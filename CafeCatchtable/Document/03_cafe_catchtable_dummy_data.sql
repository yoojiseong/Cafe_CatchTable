--------------------------------------------------------------------------------
-- 5. 예약 (RESERVATION) 데이터 - 11월 한 달간 200개
--------------------------------------------------------------------------------
BEGIN
    FOR i IN 1..200 LOOP
        INSERT INTO RESERVATION (
            MEMBER_ID, SEAT_ID, START_DT, END_DT, 
            VISITOR_COUNT, STATUS, 
            ACTUAL_IN, ACTUAL_OUT, CREATED_AT
        ) VALUES (
            'user' || (MOD(i, 50) + 1),                                                   -- 유저 1~50 분산
            MOD(i, 8) + 1,                                                                -- 좌석 1~8 분산
            TO_DATE('2026-11-01 10:00:00', 'YYYY-MM-DD HH24:MI:SS') + MOD(i * 3, 30),     -- 11월 날짜 분산
            TO_DATE('2026-11-01 12:00:00', 'YYYY-MM-DD HH24:MI:SS') + MOD(i * 3, 30),     -- 2시간 뒤 종료
            MOD(i, 4) + 1,                                                                -- 방문 인원 1~4명
            CASE 
                WHEN MOD(i, 5) = 0 THEN '노쇼'
                WHEN MOD(i, 5) = 1 THEN '예약취소'
                WHEN MOD(i, 5) = 2 THEN '이용완료'
                ELSE '예약완료'
            END,                                                                          -- 상태 다채롭게 분산
            CASE WHEN MOD(i, 5) = 2 THEN TO_DATE('2026-11-01 10:05:00', 'YYYY-MM-DD HH24:MI:SS') + MOD(i * 3, 30) ELSE NULL END,
            CASE WHEN MOD(i, 5) = 2 THEN TO_DATE('2026-11-01 12:00:00', 'YYYY-MM-DD HH24:MI:SS') + MOD(i * 3, 30) ELSE NULL END,
            TO_DATE('2026-10-25 10:00:00', 'YYYY-MM-DD HH24:MI:SS') + MOD(i * 3, 30)
        );
    END LOOP;
END;
/


